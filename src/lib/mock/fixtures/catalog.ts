function pricing(
  inputPerMillion: number | null,
  outputPerMillion: number | null,
  cachedInputPerMillion: number | null = null,
): ModelPricing {
  return {
    currency: "USD",
    unit: "per_1m_tokens",
    inputPerMillion,
    outputPerMillion,
    cachedInputPerMillion,
    updatedAt: SNAPSHOT_AT,
    snapshotId: SNAPSHOT_ID,
  };
}

function endpoint(
  id: string,
  provider: string,
  status: ModelEndpoint["status"],
  latencyMs: number | null,
  throughputTokensPerSecond: number | null,
  supportsStreaming: boolean,
  routingModes: RoutingMode[],
): ModelEndpoint {
  return {
    id,
    provider,
    status,
    latencyMs,
    throughputTokensPerSecond,
    supportsStreaming,
    routingModes,
  };
}

